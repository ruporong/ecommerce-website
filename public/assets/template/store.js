function updateCartUI() {
  const count = cart.reduce((acc, item) => acc + item.quantity, 0);
  $('.cart-count').text(count);
  
  const container = $('#cart-items');
  container.empty();
  
  if (cart.length === 0) {
    container.html('<div class="text-center text-gray-500 mt-10">Your bag is currently empty.</div>');
    $('#cart-subtotal').text('৳0');
    return;
  }
  
  let subtotal = 0;
  cart.forEach((item, index) => {
    subtotal += item.price * item.quantity;
    container.append(`
      <div class="flex gap-4 mb-6 relative">
        <img src="${item.image}" class="w-20 h-28 object-cover rounded-md" alt="${item.name}">
        <div class="flex-1 flex flex-col justify-between py-1">
          <div>
            <h4 class="font-serif text-sm">${item.name}</h4>
            <p class="text-xs text-gray-500 mb-1">Size: ${item.size} | Color: ${item.color}</p>
            <p class="text-sm font-medium">${formatPrice(item.price)}</p>
          </div>
          <div class="flex items-center gap-3">
            <button class="text-gray-400 hover:text-charcoal transition-colors btn-decrease" data-index="${index}">-</button>
            <span class="text-sm">${item.quantity}</span>
            <button class="text-gray-400 hover:text-charcoal transition-colors btn-increase" data-index="${index}">+</button>
          </div>
        </div>
        <button class="absolute top-0 right-0 text-gray-400 hover:text-charcoal btn-remove" data-index="${index}">
          <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5"><path d="M18 6L6 18M6 6l12 12"/></svg>
        </button>
      </div>
    `);
  });
  
  $('#cart-subtotal').text(formatPrice(subtotal));
}

function updateWishlistUI() {
  $('.wishlist-count').text(wishlist.length);
}

function addToCart(product, size = 'S', color = 'Burgundy') {
  const existing = cart.find(i => i.id === product.id && i.size === size && i.color === color);
  if (existing) {
    existing.quantity += 1;
  } else {
    cart.push({ ...product, quantity: 1, size, color });
  }
  localStorage.setItem('elane_cart', JSON.stringify(cart));
  updateCartUI();
  
  // Show toast or open drawer
  $('#cart-drawer').removeClass('translate-x-full');
  $('#global-overlay').removeClass('opacity-0 pointer-events-none');
}

function toggleWishlist(productId) {
  if (wishlist.includes(productId)) {
    wishlist = wishlist.filter(id => id !== productId);
  } else {
    wishlist.push(productId);
  }
  localStorage.setItem('elane_wishlist', JSON.stringify(wishlist));
  updateWishlistUI();
  renderProducts(); // re-render to update icons
}

