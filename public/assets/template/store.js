  $(document).on('click', '.btn-decrease', function() {
    const idx = $(this).data('index');
    if (cart[idx].quantity > 1) {
      cart[idx].quantity -= 1;
    } else {
      cart.splice(idx, 1);
    }
    localStorage.setItem('elane_cart', JSON.stringify(cart));
    updateCartUI();
  });
  
